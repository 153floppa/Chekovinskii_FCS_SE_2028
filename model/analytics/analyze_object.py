"""
Модуль AI-анализа объекта коммерческой недвижимости через OpenAI API.

Принимает данные объекта и контекст предсказания модели,
возвращает структурированный инвестиционный отчёт.
"""

import os
import json


SYSTEM_PROMPT = """Ты — аналитик коммерческой недвижимости. На входе ты получаешь JSON с параметрами одного объекта street-retail (Россия).
Твоя задача — выдать клиенту-инвестору структурированный мини-отчёт о потенциале объекта.

═══════════════════════════════════════════════════════════════
ПРИНЦИПЫ ОЦЕНКИ (используй их как методологическую базу)
═══════════════════════════════════════════════════════════════

Главная идея: объект тем привлекательнее, чем сильнее в его радиусе ПЕРЕВЕС спроса (домохозяйства × платёжеспособность × трафик) над ПРЕДЛОЖЕНИЕМ (плотность коммерческих помещений, конкуренты, ставки).

Конкретные правила приоритизации:

1. ЦЕНА КВ.М. ОТНОСИТЕЛЬНО ОКРУЖЕНИЯ
   Сравнивай Цена (за м²) с avg500, avg1000, med500, med1000.
   Чем ниже цена объекта относительно средних/медианных по радиусу — тем выше приоритет.
   Это самый сильный сигнал (по feature importance avg500 = 14.7, Общая площадь = 12.7 — топ-2 фактора модели).
   Учитывай этаж: 1 этаж дороже 2+ и подвалов, это нормально.

2. ПЛОТНОСТЬ ДОМОХОЗЯЙСТВ vs КОММЕРЦИИ
   Считай прокси-метрику: Квартир500 / (сумма коммерческих POI в 500м).
   Коммерческие POI = Пятерочка500 + Магнит500 + ПВЗ500 + Аптека500 + Ресторан500 + Быстропит500 + Пекарня500 + Бар500 + Пиццерия500 + Фитнес500 + Кб500 + Лаборатория500.
   Чем выше отношение — тем больше «недокормленность» локации коммерцией → тем интереснее объект.

3. ТРАНСПОРТНАЯ ДОСТУПНОСТЬ
   Остановка50/100/150 и ОстановкаMIN — индикатор пешеходного потока.
   Остановка в 50–150м = поток мимо двери. >300м = трафик слабый.

4. ЯКОРНЫЕ ТОЧКИ ПРИТЯЖЕНИЯ
   Близкие (MIN < 200м) Пятерочка/Магнит/Перекрёсток/Чижик, Аптека, ПВЗ, школа/детсад, фитнес — генераторы регулярного трафика.
   Но если их СЛИШКОМ много и они того же профиля — это перенасыщение, минус.

5. ФОРМАТ ПОМЕЩЕНИЯ
   Этаж = 1 — street-retail, базовый сценарий.
   Этаж = -1 или 2+ — сильное ограничение по арендаторам, дисконт.
   Малая площадь (<20 м²) — узкий пул (ПВЗ, кофейня, нейл). Большая (>150 м²) — продуктовый/аптека.

6. ВОЗРАСТ ОКРУЖЕНИЯ
   Год200/Год500 < 1980 — старый жилой, низкая платёжеспособность, но стабильный спальный трафик.
   Год > 2010 — новый ЖК, выше доход, но люди ездят на машинах, пешеходный трафик может быть низким.

═══════════════════════════════════════════════════════════════
ФОРМАТ ВЫВОДА (строго соблюдать)
═══════════════════════════════════════════════════════════════

# Объект: [адрес], [Район], [Площадь] м², этаж [Этаж]

## Краткий вердикт
2–3 предложения. Стоит ли смотреть, главный аргумент за и против.
Балл: от 1 до 10. Метка: 🟢 ИНТЕРЕСНО / 🟡 СРЕДНЕ / 🔴 ПРОПУСКАТЬ

## Ключевые цифры
- Цена за м²: X руб vs avg500 Y руб (отклонение ±Z%)
- Площадь: X м², этаж: N
- Домохозяйств в 500м: X
- Коммерческих POI в 500м: X
- Соотношение домохозяйств / коммерции (500м): X

## Разбор по факторам

### 1. Ценовая позиция [🟢/🟡/🔴]
Как объект стоит относительно avg500/avg1000/med500/med1000.

### 2. Спрос: население vs предложение [🟢/🟡/🔴]
Домохозяйства в 500/1000м, насколько перегружено коммерцией.

### 3. Транспорт и пешеходный поток [🟢/🟡/🔴]
Близость остановок (Остановка50/100/150/MIN).

### 4. Якорные генераторы трафика [🟢/🟡/🔴]
Что в шаговой доступности (<150–200м).

### 5. Конкурентное насыщение [🟢/🟡/🔴]
Перебор каких категорий, нехватка каких.

### 6. Возраст и качество окружения [🟢/🟡/🔴]
Год200/Год500 — платёжеспособность окружения.

## Гипотезы об арендаторах
2–4 варианта: от наиболее вероятного к менее.

## Что проверить ногами
3–5 конкретных пунктов для инвестора.

═══════════════════════════════════════════════════════════════
ТОН: сухо, по делу, с цифрами. Не лей воду. Если слабый объект — ставь 🔴.
═══════════════════════════════════════════════════════════════
"""


def analyze_object(
    full_object: dict,
    predicted_price: float,
    real_price: float,
    margin_pct: float,
    model: str = "gpt-5.5",
    max_tokens: int = 8000,
) -> str:
    """
    Запрашивает AI-анализ объекта недвижимости через OpenAI API.

    Args:
        full_object: Полный JSON объекта с параметрами
        predicted_price: Предсказанная моделью полная цена (руб)
        real_price: Реальная полная цена (руб)
        margin_pct: Недооценка в процентах
        model: Имя модели OpenAI
        max_tokens: Максимальное количество токенов ответа

    Returns:
        Текст структурированного анализа от AI

    Raises:
        Exception: При ошибке API или пустом ответе
    """
    from openai import OpenAI

    client = OpenAI(
        api_key=os.getenv("PROXYAPI_KEY", ""),
        base_url="https://api.proxyapi.ru/openai/v1"
    )

    object_json = json.dumps(full_object, ensure_ascii=False, indent=2)

    user_prompt = f"""ВХОДНЫЕ ДАННЫЕ ОБЪЕКТА:

{object_json}

ДОПОЛНИТЕЛЬНЫЙ КОНТЕКСТ:
- Модель предсказала цену: ₽{predicted_price:,.0f}
- Реальная цена: ₽{real_price:,.0f}
- Потенциальная недооценка: {margin_pct:.1f}%

Проанализируй этот объект по всем критериям выше и выдай структурированный отчёт."""

    response = client.chat.completions.create(
        model=model,
        max_completion_tokens=max_tokens,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt},
        ]
    )

    analysis = response.choices[0].message.content
    if not analysis or analysis.strip() == "":
        raise ValueError("Модель вернула пустой ответ")

    return analysis
